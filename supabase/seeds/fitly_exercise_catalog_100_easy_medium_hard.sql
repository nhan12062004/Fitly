do $fitly_cleanup$
declare
  v_legacy_count integer;
  v_reference_count integer;
begin
  select count(*) into v_legacy_count
  from public.exercises as exercise
  join fitly_legacy_exercise_ids as legacy on legacy.id = exercise.id;

  if v_legacy_count <> 0 and v_legacy_count <> 100 then
    raise exception 'Fitly catalog replacement expected either zero or 100 legacy exercise IDs, found %', v_legacy_count;
  end if;

  select count(*) into v_reference_count
  from (
    select weekly.exercise_id
    from public.weekly_plan_exercises as weekly
    join fitly_legacy_exercise_ids as legacy on legacy.id = weekly.exercise_id
    union all
    select daily.exercise_id
    from public.daily_exercise_sessions as daily
    join fitly_legacy_exercise_ids as legacy on legacy.id = daily.exercise_id
    union all
    select snapshot.exercise_id
    from public.daily_workout_session_exercises as snapshot
    join fitly_legacy_exercise_ids as legacy on legacy.id = snapshot.exercise_id
  ) as references_to_legacy_catalog;

  if v_reference_count > 0 then
    raise exception 'Fitly catalog replacement stopped: % plan/history row(s) still reference legacy exercises. Preserve or migrate those records before deleting the old catalog.', v_reference_count;
  end if;
end
$fitly_cleanup$;

delete from public.exercises as exercise
using fitly_legacy_exercise_ids as legacy
where exercise.id = legacy.id;

