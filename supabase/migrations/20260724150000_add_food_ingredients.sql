create table if not exists public.food_ingredients (
  id bigint generated by default as identity primary key,
  food_id uuid not null references public.foods(id) on delete cascade,
  ingredient_name text not null,
  amount numeric,
  unit text,
  preparation_note text,
  is_optional boolean not null default false,
  order_index integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint food_ingredients_amount_check check (amount is null or amount >= 0),
  constraint food_ingredients_order_index_check check (order_index >= 0)
);

create index if not exists food_ingredients_food_id_idx on public.food_ingredients(food_id);

alter table public.food_ingredients enable row level security;

create policy food_ingredients_active_read on public.food_ingredients
  for select to anon, authenticated
  using (exists (select 1 from public.foods where foods.id = food_ingredients.food_id and foods.is_active = true));

create policy food_ingredients_admin_write on public.food_ingredients
  for all to authenticated
  using (exists (select 1 from public.profiles where profiles.id = auth.uid() and profiles.role = 'admin'))
  with check (exists (select 1 from public.profiles where profiles.id = auth.uid() and profiles.role = 'admin'));

revoke insert, update, delete, truncate on table public.food_ingredients from anon, authenticated;
grant select on table public.food_ingredients to anon, authenticated;
