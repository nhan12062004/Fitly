-- Recipes are complete dishes. public.foods remains the ingredient/basic-food catalog.
create table if not exists public.recipes (
  id text primary key,
  name text not null,
  name_en text,
  description text,
  meal_type text[] not null default '{}'::text[],
  dietary_restrictions text[] not null default '{}'::text[],
  diet_styles text[] not null default '{}'::text[],
  goal_type text[] not null default '{}'::text[],
  price_level text not null default 'medium',
  estimated_cost_min_vnd integer,
  estimated_cost_max_vnd integer,
  calories numeric,
  protein numeric,
  carbs numeric,
  fat numeric,
  serving_size numeric,
  serving_unit text,
  cooking_time_minutes integer,
  cooking_difficulty text,
  allergens text[] not null default '{}'::text[],
  instructions jsonb not null default '{"preparation": [], "steps": [], "tips": []}'::jsonb,
  image_url text,
  region text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint recipes_price_level_check check (price_level in ('low', 'medium', 'high')),
  constraint recipes_cooking_difficulty_check check (cooking_difficulty is null or cooking_difficulty in ('easy', 'medium', 'hard')),
  constraint recipes_meal_type_check check (meal_type <@ array['breakfast', 'lunch', 'dinner', 'snack', 'pre_workout', 'post_workout']::text[]),
  constraint recipes_dietary_restrictions_check check (dietary_restrictions <@ array['vegetarian', 'vegan']::text[]),
  constraint recipes_diet_styles_check check (diet_styles <@ array['clean', 'high_protein', 'low_carb', 'balanced']::text[]),
  constraint recipes_allergens_check check (allergens <@ array['peanut', 'tree_nuts', 'milk', 'egg', 'soy', 'wheat', 'fish', 'shellfish', 'sesame']::text[]),
  constraint recipes_calories_check check (calories is null or calories >= 0),
  constraint recipes_protein_check check (protein is null or protein >= 0),
  constraint recipes_carbs_check check (carbs is null or carbs >= 0),
  constraint recipes_fat_check check (fat is null or fat >= 0),
  constraint recipes_serving_size_check check (serving_size is null or serving_size > 0),
  constraint recipes_cooking_time_check check (cooking_time_minutes is null or cooking_time_minutes >= 0),
  constraint recipes_cost_min_check check (estimated_cost_min_vnd is null or estimated_cost_min_vnd >= 0),
  constraint recipes_cost_max_check check (estimated_cost_max_vnd is null or estimated_cost_max_vnd >= 0),
  constraint recipes_cost_range_check check (
    estimated_cost_min_vnd is null or estimated_cost_max_vnd is null or estimated_cost_max_vnd >= estimated_cost_min_vnd
  ),
  constraint recipes_instructions_shape_check check (
    jsonb_typeof(instructions) = 'object'
    and instructions ?& array['preparation', 'steps', 'tips']
    and jsonb_typeof(instructions->'preparation') = 'array'
    and jsonb_typeof(instructions->'steps') = 'array'
    and jsonb_typeof(instructions->'tips') = 'array'
  )
);

create table if not exists public.recipe_ingredients (
  id bigint generated by default as identity primary key,
  recipe_id text not null references public.recipes(id) on delete cascade,
  food_id uuid references public.foods(id) on delete set null,
  ingredient_name text not null,
  amount numeric,
  unit text,
  preparation_note text,
  is_optional boolean not null default false,
  order_index integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint recipe_ingredients_amount_check check (amount is null or amount >= 0),
  constraint recipe_ingredients_order_index_check check (order_index >= 0)
);

alter table public.weekly_food_items
  add column if not exists recipe_id text references public.recipes(id) on delete set null;

-- Rest-day marker rows existed before recipe support and intentionally have neither reference.
alter table public.weekly_food_items
  drop constraint if exists weekly_food_items_food_or_recipe_check;
alter table public.weekly_food_items
  add constraint weekly_food_items_food_or_recipe_check
  check (is_rest_day = true or food_id is not null or recipe_id is not null) not valid;

create index if not exists recipes_is_active_idx on public.recipes (is_active);
create index if not exists recipes_price_level_idx on public.recipes (price_level);
create index if not exists recipes_meal_type_gin_idx on public.recipes using gin (meal_type);
create index if not exists recipes_dietary_restrictions_gin_idx on public.recipes using gin (dietary_restrictions);
create index if not exists recipes_diet_styles_gin_idx on public.recipes using gin (diet_styles);
create index if not exists recipes_goal_type_gin_idx on public.recipes using gin (goal_type);
create index if not exists recipes_allergens_gin_idx on public.recipes using gin (allergens);
create index if not exists recipe_ingredients_recipe_id_idx on public.recipe_ingredients (recipe_id);
create index if not exists recipe_ingredients_food_id_idx on public.recipe_ingredients (food_id);
create index if not exists weekly_food_items_recipe_id_idx on public.weekly_food_items (recipe_id);

alter table public.recipes enable row level security;
alter table public.recipe_ingredients enable row level security;

create policy recipes_active_read on public.recipes
  for select to authenticated
  using (is_active = true);
create policy recipes_admin_write on public.recipes
  for all to authenticated
  using (exists (select 1 from public.profiles where profiles.id = auth.uid() and profiles.role = 'admin'))
  with check (exists (select 1 from public.profiles where profiles.id = auth.uid() and profiles.role = 'admin'));

create policy recipe_ingredients_active_read on public.recipe_ingredients
  for select to authenticated
  using (exists (select 1 from public.recipes where recipes.id = recipe_ingredients.recipe_id and recipes.is_active = true));
create policy recipe_ingredients_admin_write on public.recipe_ingredients
  for all to authenticated
  using (exists (select 1 from public.profiles where profiles.id = auth.uid() and profiles.role = 'admin'))
  with check (exists (select 1 from public.profiles where profiles.id = auth.uid() and profiles.role = 'admin'));

revoke insert, update, delete, truncate on table public.recipes from anon, authenticated;
revoke insert, update, delete, truncate on table public.recipe_ingredients from anon, authenticated;
grant select on table public.recipes to authenticated;
grant select on table public.recipe_ingredients to authenticated;
